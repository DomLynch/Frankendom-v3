// Bakes the sim's blade sweeps for the hero's picked clips (data/hero-clips.json) into src/fight/blade-picks.ts: V1's scripts/bake-blades.mjs
// (@ 82a994d15) for one (rig, weapon), with each row's clip and contact key in place of the path's own clip and `source`. Every other sweep
// stays V1's (src/fight/blade-paths.ts, untouched). Needs three.js, which V3 does not install: on the VPS, in a scratch clone,
//   npm i --no-save three@0.186.0 && node scripts/hero-clips/bake-blades.mjs
import fs from 'node:fs/promises';
import { AnimationMixer, Vector3 } from 'three';
import { GLTFLoader } from 'three/addons/loaders/GLTFLoader.js';
import { swingProgress } from '../../src/fight/blade.ts';
import { WEAPONS, total } from '../../src/fight/moves.ts';
globalThis.ProgressEvent = class { constructor(_, fields) { Object.assign(this, fields); } };
const rows = JSON.parse(await fs.readFile('data/hero-clips.json', 'utf8'));
const load = async (file) => {   // geometry-free load: nodes, transforms and clips are all a bake needs (as V1's)
  const bytes = await fs.readFile(file), size = bytes.readUInt32LE(12), json = JSON.parse(bytes.subarray(20, 20 + size));
  json.images = []; json.textures = []; json.materials = (json.materials || []).map((m) => ({ name: m.name }));
  json.buffers[0].uri = 'data:application/octet-stream;base64,' + bytes.subarray(28 + size).toString('base64');
  return new GLTFLoader().parseAsync(JSON.stringify(json), '');
};
const asset = await load('src/assets/warrior.glb'), mixer = new AnimationMixer(asset.scene), blade = asset.scene.getObjectByName(rows.blade.node);
if (!blade) throw new Error(`warrior.glb has no node ${rows.blade.node}`);
const weapon = WEAPONS[rows.weapon], strike = rows.blade.contact, paths = {};
for (const row of rows.clips) {
  const clip = asset.animations.find((c) => c.name === row.clip); if (!clip) throw new Error(`warrior.glb has no clip ${row.clip}: run scripts/hero-clips/build.py`);
  const source = (row.contact - row.from) / (row.to - row.from);
  for (const kind of row.paths) {
    const spec = weapon.paths[kind]; if (!spec) throw new Error(`${rows.weapon} has no path ${kind}`);
    const length = total(spec), action = mixer.clipAction(clip).play();
    paths[kind] = Array.from({ length: length + 1 }, (_, age) => {
      mixer.setTime(Math.min(0.999999, swingProgress(age / length, spec.windup / length, source)) * clip.duration); asset.scene.updateMatrixWorld(true);
      return strike.flatMap((y) => blade.localToWorld(new Vector3(0, y, 0)).toArray().map((v) => +v.toFixed(5)));
    });
    action.stop(); mixer.uncacheClip(clip);
  }
}
await fs.writeFile('src/fight/blade-picks.ts', '// Generated by scripts/hero-clips/bake-blades.mjs from data/hero-clips.json and src/assets/warrior.glb. Do not hand-edit.\n'
  + `// The sweeps of the hero's picked clips, by path id, for ${rows.weapon} on the ${rows.rig} rig (laid over V1's blade-paths.ts by src/hero-clips.ts).\n`
  + 'export const BLADE_PICKS: Record<string, number[][]> = ' + JSON.stringify(paths) + ';\n');
console.log(`${rows.weapon}@${rows.rig}: ${Object.keys(paths).join(', ')} (${Object.values(paths).reduce((n, p) => n + p.length, 0)} fixed-tick poses)`);
